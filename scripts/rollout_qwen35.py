#!/usr/bin/env python
"""Strict self-generated APIGen rollout for text-only Qwen3.5 models.

Qwen3.5 emits its native XML-like tool-call syntax, so this baseline is kept
separate from the Qwen3+AE runner. It supplies only original human messages;
assistant messages and calls are generated by Qwen3.5. Logged tool results are
replayed only after an exact canonical call match, and their execution time is
not measured.
"""
import argparse
import json
import re
import sys
import time
from pathlib import Path

import torch
from transformers import AutoModelForImageTextToText, AutoProcessor

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from kv_action.data import canonical_action, load_records
from scripts.rollout_trajectory import get_tool_pairs, user_messages


FUNCTION = re.compile(r"<function=([^>]+)>\s*(.*?)\s*</function>", re.DOTALL)
PARAMETER = re.compile(r"<parameter=([^>]+)>\s*(.*?)\s*</parameter>", re.DOTALL)


def sync(device):
    if device.type == "cuda":
        torch.cuda.synchronize(device)


def parse_qwen35_call(text):
    match = FUNCTION.search(text)
    if match is None:
        return None
    arguments = {}
    for key, value in PARAMETER.findall(match.group(2)):
        value = value.strip()
        try:
            arguments[key.strip()] = json.loads(value)
        except json.JSONDecodeError:
            arguments[key.strip()] = value
    return {"name": match.group(1).strip(), "arguments": arguments}


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--data", required=True)
    p.add_argument("--backbone", required=True)
    p.add_argument("--trajectory-index", type=int, default=0)
    p.add_argument("--max-new-tokens", type=int, default=512)
    p.add_argument("--max-agent-turns", type=int, default=8)
    p.add_argument("--output", required=True)
    p.add_argument("--print-predictions", action="store_true")
    args = p.parse_args()

    records = load_records(args.data)
    if not 0 <= args.trajectory_index < len(records):
        raise ValueError(f"--trajectory-index must be in [0, {len(records) - 1}]")
    record = records[args.trajectory_index]
    tools = json.loads(record["tools"]) if isinstance(record["tools"], str) else record["tools"]
    tools = [tool for tool in tools if tool.get("name") != "think"]
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    dtype = torch.bfloat16 if device.type == "cuda" and torch.cuda.is_bf16_supported() else torch.float32
    load_start = time.perf_counter()
    processor = AutoProcessor.from_pretrained(args.backbone)
    model = AutoModelForImageTextToText.from_pretrained(args.backbone, dtype=dtype).to(device).eval()
    tokenizer = processor.tokenizer
    sync(device)
    load_s = time.perf_counter() - load_start

    messages = [{"role": "system", "content": record.get("system", "")}]
    pairs, pair_index, events = get_tool_pairs(record, False), 0, []
    sync(device)
    rollout_start = time.perf_counter()
    for user_index, user_text in enumerate(user_messages(record)):
        messages.append({"role": "user", "content": user_text})
        for assistant_turn in range(args.max_agent_turns):
            rendered = processor.apply_chat_template(
                messages, tools=tools, add_generation_prompt=True, enable_thinking=False, tokenize=False
            )
            inputs = processor(text=[rendered], return_tensors="pt").to(device)
            sync(device)
            start = time.perf_counter()
            output = model.generate(
                **inputs, max_new_tokens=args.max_new_tokens, do_sample=False,
                eos_token_id=tokenizer.eos_token_id, pad_token_id=tokenizer.eos_token_id,
            )
            sync(device)
            decode_s = time.perf_counter() - start
            raw = tokenizer.decode(output[0, inputs.input_ids.size(1) :], skip_special_tokens=False)
            predicted = parse_qwen35_call(raw)
            event = {"user_turn": user_index, "assistant_turn": assistant_turn, "raw": raw, "decode_s": decode_s,
                     "generated_tokens": int(output.size(1) - inputs.input_ids.size(1))}
            if predicted is None:
                messages.append({"role": "assistant", "content": raw.replace("<|im_end|>", "").strip()})
                event["kind"] = "text"
                events.append(event)
                break
            target, observation = pairs[pair_index] if pair_index < len(pairs) else (None, "")
            exact = target is not None and canonical_action(predicted) == canonical_action(target)
            if exact:
                result_source, pair_index = "recorded_match", pair_index + 1
            else:
                observation = json.dumps({"error": "Generated call does not match the next logged call."})
                result_source = "local_error"
            messages.append({"role": "assistant", "content": "", "tool_calls": [{"type": "function", "function": {"name": predicted["name"], "arguments": predicted["arguments"]}}]})
            messages.append({"role": "tool", "content": observation})
            event.update({"kind": "tool_call", "prediction": canonical_action(predicted),
                          "target": canonical_action(target) if target is not None else None,
                          "exact_match": exact, "tool_result_source": result_source})
            events.append(event)
        else:
            raise RuntimeError(f"Exceeded --max-agent-turns={args.max_agent_turns} after user turn {user_index}")
    sync(device)
    wall_s = time.perf_counter() - rollout_start
    calls = [event for event in events if event["kind"] == "tool_call"]
    summary = {
        "model": args.backbone, "trajectory_index": args.trajectory_index, "tool_result_mode": "strict",
        "model_load_s": load_s, "rollout_wall_s": wall_s, "assistant_turns": len(events), "tool_calls": len(calls),
        "canonical_exact_match": sum(event["exact_match"] for event in calls) / len(calls) if calls else 0.0,
        "generated_tokens": sum(event["generated_tokens"] for event in events),
        "replay_protocol": "Only logged human messages are inputs; all assistant turns are model generated. Logged observations are replayed only after an exact call match; tool execution time is excluded.",
    }
    report = {"summary": summary, "events": events, "unused_logged_tool_pairs": len(pairs) - pair_index}
    output = Path(args.output)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(json.dumps(report, ensure_ascii=False, indent=2), encoding="utf-8")
    print(json.dumps(summary, ensure_ascii=False, indent=2))
    if args.print_predictions:
        for event in events:
            print(f"\n--- user {event['user_turn']} assistant {event['assistant_turn']} ({event['kind']}) ---\n{event['raw']}")
    print(f"Saved report to {output}")


if __name__ == "__main__":
    main()
